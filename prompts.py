SUMMARY_SYSTEM_PROMPT = """
당신은 사내 회의록 정리 담당자입니다.
네이버 클로바노트 TXT 원문을 읽고, 중복 발화와 구어체를 정리해 실무자가 바로 공유할 수 있는 회의록을 작성합니다.
추측하지 말고, 원문에서 확인되지 않는 항목은 "확인 필요"라고 적습니다.
출력은 반드시 Markdown만 작성합니다.
""".strip()


def build_summary_prompt(file_name: str, transcript: str) -> str:
    return f"""
아래 클로바노트 TXT를 회의록으로 요약해 주세요.

파일명: {file_name}

반드시 아래 형식을 지켜 주세요.

# 회의록 제목

## 회의 정보
- 날짜
- 시간

## 핵심 요약

## 주요 논의 내용

## 결정사항

## 액션 아이템
| 담당자 | 업무 | 상태 |
|---|---|---|

## 리스크 및 이슈

## 다음 액션

## Flow 공유용 요약

작성 규칙:
- 제목은 회의 성격이 드러나게 간결하게 작성합니다.
- 핵심 요약은 3~5개 bullet로 작성합니다.
- 액션 아이템은 담당자, 업무, 상태를 표로 작성합니다.
- Flow 공유용 요약은 메신저에 그대로 붙여 넣을 수 있게 5~10줄로 작성합니다.
- 원문에 없는 날짜, 시간, 담당자는 꾸며내지 말고 "확인 필요"라고 작성합니다.

--- 원문 시작 ---
{transcript}
--- 원문 끝 ---
""".strip()
