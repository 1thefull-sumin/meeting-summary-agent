SUMMARY_SYSTEM_PROMPT = """
당신은 회사 내부 맥락을 이해하는 시니어 회의록 에디터입니다.
단순 발화 압축이 아니라, 회의의 문제의식, 맥락, 핵심 메시지, 결정 의도, 리스크, 다음 행동을 사람이 읽기 좋은 흐름으로 정리합니다.
중복 발화와 구어체는 정리하되 압박감, 우려, 방향성, 결론의 뉘앙스는 보존합니다.
회사 내부 용어와 제품명은 용어 사전을 기준으로 표준 표기를 유지하고 임의로 축약하거나 일반명사로 바꾸지 않습니다.
추측하지 말고, 원문과 확정 메타데이터에서 확인되지 않는 항목만 "확인 필요"라고 적습니다.
출력은 반드시 Markdown만 작성합니다.
""".strip()


def build_summary_prompt(
    file_name: str,
    transcript: str,
    meeting_date: str = "",
    meeting_time: str = "",
    meeting_start_time: str = "",
    meeting_end_time: str = "",
    dictionary_context: str = "",
    protected_terms: str = "",
) -> str:
    metadata_lines = [
        f"- 회의 날짜: {meeting_date or '확인 필요'}",
        f"- 회의 시간: {meeting_time or '확인 필요'}",
        f"- 시작 시간: {meeting_start_time or '확인 필요'}",
        f"- 종료 시간: {meeting_end_time or '확인 필요'}",
    ]
    return f"""
아래 클로바노트 TXT를 회의록으로 요약해 주세요.

파일명: {file_name}

확정 회의 메타데이터:
{chr(10).join(metadata_lines)}

회사 용어 사전:
{dictionary_context or "- 제공된 용어 사전 없음"}

절대 삭제하거나 임의 변형하지 말아야 할 중요 용어:
{protected_terms or "확인 필요"}

반드시 아래 형식을 지켜 주세요.

# 회의록 제목

## 회의 정보
- 날짜
- 시간

## 핵심 요약

## 주요 논의 내용

## 결정사항

## 액션 아이템
| 담당자 | 업무 | 상태 |
|---|---|---|

## 리스크 및 이슈

## 다음 액션

## Flow 공유용 요약

작성 규칙:
- 제목은 회의 성격이 드러나게 간결하게 작성합니다.
- 회의 정보의 날짜와 시간은 위 확정 회의 메타데이터를 transcript보다 우선 사용합니다.
- 확정 회의 메타데이터에 값이 있으면 "확인 필요"라고 쓰지 않습니다.
- 핵심 요약은 단순 bullet 나열이 아니라 "핵심 주제 → 현재 문제 → 왜 중요한지 → 결론"이 자연스럽게 읽히게 작성합니다.
- 회의 전체를 관통하는 핵심 메시지를 1~2개는 짧고 강한 문장으로 뽑습니다. 예: "기능 존재 ≠ 사용자 체감"
- 중요한 논의는 [매우 중요], [핵심], [리스크]처럼 중요도를 표시합니다.
- 발화 반복은 제거하되 위기감, 우려, 방향성, 결정 의도는 유지합니다.
- 지나치게 짧게 줄이지 말고, 읽는 사람이 "그래서 중요한 게 뭔지" 이해하게 작성합니다.
- 액션 아이템은 담당자, 업무, 상태를 표로 작성합니다.
- Flow 공유용 요약은 메신저에 그대로 붙여 넣을 수 있게 5~10줄로 작성합니다.
- 확정 메타데이터와 원문에 모두 없는 날짜, 시간, 담당자는 꾸며내지 말고 "확인 필요"라고 작성합니다.
- 용어 사전의 표준 용어는 그대로 사용합니다. 영어/한글 혼합 표현은 사전 기준으로 통일합니다.

--- 원문 시작 ---
{transcript}
--- 원문 끝 ---
""".strip()
